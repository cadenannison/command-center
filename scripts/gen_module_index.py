"""Build docs/generated/module-index.md: one line per source module, from its docstring.

`mise run gen:build` and `gen:check` reach this through scripts/gen_docs.py, which asks for
`build_module_index` and keeps the file with the other generated ones. The index has no line counts,
so it changes only when a module is added, removed or has its first docstring sentence edited.
"""

import ast
import re
from pathlib import Path

MAX_SUMMARY = 120
_SENTENCE_END = re.compile(r"(?<!e\.g\.)(?<!i\.e\.)(?<=[.!?])\s")


class ModuleIndexError(ValueError):
    """A source file could not be parsed; the message names it."""


def _summary(path: Path) -> str:
    """The first sentence of the first docstring paragraph, on one line and at most MAX_SUMMARY."""
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except SyntaxError as exc:
        msg = f"{path.name}: cannot parse ({exc.msg}, line {exc.lineno})"
        raise ModuleIndexError(msg) from exc
    docstring = ast.get_docstring(tree)
    if not docstring:
        return "(no docstring)"
    paragraph = " ".join(docstring.split("\n\n", 1)[0].split())
    first = _SENTENCE_END.split(paragraph, maxsplit=1)[0]
    return first if len(first) <= MAX_SUMMARY else first[: MAX_SUMMARY - 3].rstrip() + "..."


def build_module_index(source_root: Path) -> str:
    """Render the index for the modules under `source_root`, grouped by folder."""
    folders: dict[str, list[str]] = {}
    for path in sorted(source_root.rglob("*.py")):
        relative = path.relative_to(source_root)
        if path.name == "__init__.py" or "__pycache__" in relative.parts:
            continue
        folder = relative.parent.as_posix() + "/" if relative.parent.parts else ""
        folders.setdefault(folder, []).append(f"- `{path.name}`: {_summary(path)}")
    lines = [
        "# Module index",
        "",
        (
            "Generated by `mise run gen:build` from the module docstrings under"
            " `src/command_center/`. Do not edit."
        ),
        "",
        (
            "One line per module: its first docstring sentence. Use it to find the file you need"
            " instead of listing or opening folders. Layer rules and import boundaries:"
            " `docs/MAP.md`."
        ),
    ]
    for folder in sorted(folders):
        lines += ["", f"## {folder or '(root)'}", *folders[folder]]
    return "\n".join(lines) + "\n"
